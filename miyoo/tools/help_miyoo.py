#!/usr/bin/env python3
"""Write the Miyoo Mini Plus versions of help messages that name keyboard keys.

The Miyoo has no keyboard: Select held works as Shift and Start held as Control while
clicking in pointer mode, and there is no Alt or number keys. Help messages that use
<command> names already show the buttons; this rewrites the ones with literal keys.
Each help message defined again in a later file replaces the earlier one.

    help_miyoo.py <data/_ui/help.txt> <out file>
"""
import re
import sys

# Exact phrases and their Miyoo wording; '' removes a whole line holding the phrase.
REPLACE = {
    'You can also press F to search the map': 'You can also click "Find" to search the map',
    'You can also press F to search the shipyard and outfitter maps':
        'You can also click "Find" to search the shipyard and outfitter maps',
    'This can also be enabled by pressing T.': 'This can also be enabled with the "Stars" button.',
    'You can also press F to search the outfitter': 'You can also click the magnifying glass to search the outfitter',
    'You can also press F to search the shipyard for': 'You can also click the magnifying glass to search the shipyard for',
    'You can Shift+click on systems to plot a route between them, or Control+click to select a system':
        'You can hold Select and click on systems to plot a route between them, or hold Start and click to select a system',
    'Using Shift+click on a ship or outfit': 'Holding Select while clicking on a ship or outfit',
    'Using Shift+click on a category name': 'Holding Select while clicking on a category name',
    'you can hold down Shift, Control, or Alt to buy, sell, or move 5, 20, or 500 of an outfit at once, or multiple keys for larger amounts.':
        'you can hold Select, Start, or both while clicking to buy, sell, or move 5, 20, or 100 of an outfit at once.',
    'you can hold down Shift, Control, or Alt to buy 5, 20, or 500 ships at once, or multiple keys for larger amounts.':
        'you can hold Select, Start, or both while clicking to buy 5, 20, or 100 ships at once.',
    'Ctrl+click a ship icon to add it to your selection. You can also use Shift+click to select a range of ships.':
        'Hold Start and click a ship icon to add it to your selection, or hold Select and click to select a range of ships.',
    ', or select a line with the up and down arrows and press "+" or "-" (or Enter and Delete).': '.',
    'You can buy 5 tons at once by holding down Shift, 20 by holding down Control, 500 by holding down Alt, or larger amounts at a time by holding down two keys at once, or even all three.':
        'You can buy 5 tons at once by holding Select while you click, 20 by holding Start, or 100 by holding both.',
    'Use your scroll wheel or click and drag, to scroll the view.':
        'Use L1 and R1, or hold A on the list and move the pointer, to scroll the view.',
    'You can use the shortcuts B to Buy, S to Sell the ship and outfits, and R to sell the ship and retain the outfits if the planet has an outfitter.':
        'Use the Buy, Sell and Sell Hull buttons: Sell sells the ship with its outfits, and Sell Hull keeps the outfits if the planet has an outfitter.',
    'You can use the following keyboard shortcuts or the buttons to move outfits around:': 'Use these buttons to move outfits around:',
    '- "B" to buy and install outfits': '- Buy: buy and install outfits',
    '- "S" to sell outfits': '- Sell: sell outfits',
    '- "I" to install outfits': '- Install: install outfits',
    '- "U" to uninstall outfits': '- Uninstall: uninstall outfits',
    '- "C" to move outfits': '- Cargo: move outfits',
    '- "R" to move outfits': '- Store: move outfits',
    'Left click - will target an asteroid': 'A in pointer mode (tap Select) - will target an asteroid',
    'Right click - will focus your fleet': 'X in pointer mode - will focus your fleet',
    # Control groups need number keys.
    'Escorts can be saved into control groups by pressing Control+number key.': '',
    'Escorts can be saved into control groups by pressing a number key while holding Control.': '',
}


def main():
    src, out = sys.argv[1], sys.argv[2]
    lines = open(src).read().split('\n')
    used, result, block, changed = set(), ['# Miyoo Mini Plus help, generated by miyoo/tools/help_miyoo.py.', ''], [], False

    def flush():
        if block and changed:
            result.extend(block + [''])

    for line in lines:
        if re.match(r'^help "', line):
            flush()
            block, changed = [line], False
            continue
        if not block:
            continue
        if line and not line[0].isspace():
            flush()
            block, changed = [], False
            continue
        for old, new in REPLACE.items():
            if old in line:
                used.add(old)
                changed = True
                line = None if new == '' else line.replace(old, new)
                if line is None:
                    break
        if line is not None:
            block.append(line)
    flush()
    missing = set(REPLACE) - used
    assert not missing, f'phrases not found upstream: {missing}'
    with open(out, 'w') as f:
        f.write('\n'.join(result).rstrip('\n') + '\n')
    print(f'{len(used)} phrases rewritten into {out}')


if __name__ == '__main__':
    main()
